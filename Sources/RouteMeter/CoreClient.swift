import UniformTypeIdentifiers

private final class LocalSession: NSObject, URLSessionTaskDelegate {
    func urlSession(_ session: URLSession, task: URLSessionTask, willPerformHTTPRedirection response: HTTPURLResponse,
                    newRequest request: URLRequest, completionHandler: @escaping (URLRequest?) -> Void) {
        completionHandler(nil)
    }
}
struct AppMeterRow: Identifiable {
    let id: String
    let name: String
    let path: String
    let usage: ByteCounts
    let rate: ByteCounts
    let attribution: String
}
final class CoreClient: ObservableObject {
    @Published var sample: CoreUsage?
    @Published var directRate = ByteCounts()
    @Published var proxyRate = ByteCounts()
    @Published var unknownRate = ByteCounts()
    @Published var lastUpdate: Date?
    @Published var error: String?
    @Published var appLiveRates = false
    @Published var filter = ""
    @Published var selected = false
    private var previous: CoreUsage?
    private var perAppRate: [String: ByteCounts] = [:]
    private let root: URL
    private var manifest: URL?
    private var baseline: Baseline?
    private var loading = false
    private let delegate = LocalSession()
    private lazy var session: URLSession = {
        let config = URLSessionConfiguration.ephemeral
        config.connectionProxyDictionary = [:]
        config.timeoutIntervalForRequest = 2
        config.timeoutIntervalForResource = 4
        return URLSession(configuration: config, delegate: delegate, delegateQueue: nil)
    }()
    private struct Preference: Codable { let path: String; let selected: Bool }
    private struct Baseline: Codable {
        let epoch: String; let since: Date
        let direct: ByteCounts; let proxy: ByteCounts; let unknown: ByteCounts
        let apps: [String: ByteCounts]
    }
    init(root: URL) {
        self.root = root
        if let data = try? Data(contentsOf: root.appendingPathComponent("core-view.json")),
           let preference = try? JSONDecoder().decode(Preference.self, from: data) {
            manifest = URL(fileURLWithPath: preference.path); selected = preference.selected
        }
        if let data = try? Data(contentsOf: root.appendingPathComponent("core-baseline.json")) {
            baseline = try? JSONDecoder().decode(Baseline.self, from: data)
        }
    }
    var live: Bool { error == nil && lastUpdate.map { Date().timeIntervalSince($0) < 5 } == true }
    var started: Date {
        if let b = baseline, b.epoch == sample?.epoch { return b.since }
        guard let sample else { return Date() }
        return Date(timeIntervalSince1970: Double(sample.since)/1000)
    }
    var direct: ByteCounts { adjusted(sample?.totals.direct.counts ?? ByteCounts(), baseline?.direct) }
    var proxy: ByteCounts { adjusted(sample?.totals.proxy.counts ?? ByteCounts(), baseline?.proxy) }
    var unknown: ByteCounts { adjusted(sample?.totals.unknown.counts ?? ByteCounts(), baseline?.unknown) }
    var rows: [AppMeterRow] {
        (sample?.apps ?? []).map { app in
            let base = baseline?.epoch == sample?.epoch ? baseline?.apps[app.id] : nil
            return AppMeterRow(id: app.id, name: app.name, path: app.executable ?? "", usage: difference(app.usage.proxy.counts, base ?? ByteCounts()),
                               rate: perAppRate[app.id] ?? ByteCounts(), attribution: app.attribution)
        }.filter { ($0.usage.total > 0 || $0.rate.total > 0) && (filter.isEmpty || $0.name.localizedCaseInsensitiveContains(filter)) }
            .sorted { (appLiveRates ? $0.rate.total : $0.usage.total) > (appLiveRates ? $1.rate.total : $1.usage.total) }
    }
    var qualityWarning: String? {
        if let e = sample?.persistenceError, !e.isEmpty { return e }
        if sample?.overflow == true { return "A counter overflowed. Treat this measurement as incomplete." }
        if let n = sample?.uncertainUpload, n > 0 { return "Transfer errors left \(formatBytes(n)) of possible upload unmeasured." }
        if unknown.total > 0 { return "Unknown routing is included in Total and kept separate from Proxy." }
        return nil
    }
    var unattributedProxy: ByteCounts {
        (sample?.apps ?? []).filter { $0.attribution != "executable" }.reduce(ByteCounts()) { sum, app in
            let base = baseline?.epoch == sample?.epoch ? baseline?.apps[app.id] : nil
            return sum + difference(app.usage.proxy.counts, base ?? ByteCounts())
        }
    }
    func connect() {
        let panel = NSOpenPanel()
        panel.title = "Connect RouteMeter Core"
        panel.message = "Choose the private connection.json generated by RouteMeter Core. No system proxy settings are changed."
        panel.allowedContentTypes = [.json]
        panel.directoryURL = root.appendingPathComponent("Core/route-meter")
        guard panel.runModal() == .OK, let url = panel.url else { return }
        manifest = url; selected = true; previous = nil; error = nil
        persistPreference(); poll()
    }
    func useQX() { selected = false; persistPreference() }
    func reset() {
        guard let sample else { return }
        baseline = Baseline(epoch: sample.epoch, since: Date(), direct: sample.totals.direct.counts,
                            proxy: sample.totals.proxy.counts, unknown: sample.totals.unknown.counts,
                            apps: Dictionary(uniqueKeysWithValues: sample.apps.map { ($0.id, $0.usage.proxy.counts) }))
        if let data = try? JSONEncoder().encode(baseline) { save(data, "core-baseline.json") }
        objectWillChange.send()
    }
    func poll() {
        guard selected, !loading, let manifest else { return }
        do {
            let size = try manifest.resourceValues(forKeys: [.fileSizeKey]).fileSize ?? 0
            guard size < 65536 else { throw NSError(domain: "Core", code: 1) }
            let data = try Data(contentsOf: manifest)
            guard data.count < 65536 else { throw NSError(domain: "Core", code: 1) }
            let connection = try JSONDecoder().decode(CoreConnection.self, from: data)
            guard let url = connection.usageURL else { throw NSError(domain: "Core", code: 2) }
            var request = URLRequest(url: url)
            request.setValue("Bearer " + connection.token, forHTTPHeaderField: "Authorization")
            loading = true
            session.dataTask(with: request) { [weak self] data, response, networkError in
                DispatchQueue.main.async {
                    guard let self else { return }; self.loading = false
                    guard self.selected, networkError == nil, (response as? HTTPURLResponse)?.statusCode == 200,
                          let data, data.count < 32_000_000, let sample = try? JSONDecoder().decode(CoreUsage.self, from: data), sample.valid() else {
                        self.error = "Core unavailable or invalid data. Check that RouteMeter Core is running."; return
                    }
                    self.accept(sample)
                }
            }.resume()
        } catch { self.error = "Cannot read a valid loopback Core connection file." }
    }
    private func accept(_ next: CoreUsage) {
        directRate = ByteCounts(); proxyRate = ByteCounts(); unknownRate = ByteCounts(); perAppRate = [:]
        if let old = previous, old.instance == next.instance, next.timestamp > old.timestamp {
            let seconds = Double(next.timestamp - old.timestamp)/1000
            func rate(_ current: ByteCounts, _ before: ByteCounts) -> ByteCounts {
                let delta = difference(current, before)
                return ByteCounts(down: UInt64(min(Double(UInt64.max - 2048), Double(delta.down)/seconds)),
                                  up: UInt64(min(Double(UInt64.max - 2048), Double(delta.up)/seconds)))
            }
            directRate = rate(next.totals.direct.counts, old.totals.direct.counts)
            proxyRate = rate(next.totals.proxy.counts, old.totals.proxy.counts)
            unknownRate = rate(next.totals.unknown.counts, old.totals.unknown.counts)
            let oldApps = Dictionary(uniqueKeysWithValues: old.apps.map { ($0.id, $0) })
            for app in next.apps { perAppRate[app.id] = rate(app.usage.proxy.counts, oldApps[app.id]?.usage.proxy.counts ?? ByteCounts()) }
        }
        previous = next; sample = next; lastUpdate = Date(); error = nil
    }
    private func adjusted(_ value: ByteCounts, _ base: ByteCounts?) -> ByteCounts {
        difference(value, baseline?.epoch == sample?.epoch ? base ?? ByteCounts() : ByteCounts())
    }
    private func persistPreference() {
        guard let manifest, let data = try? JSONEncoder().encode(Preference(path: manifest.path, selected: selected)) else { return }
        save(data, "core-view.json")
    }
    private func save(_ data: Data, _ name: String) {
        let file = root.appendingPathComponent(name)
        do { try data.write(to: file, options: .atomic); try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: file.path) }
        catch { self.error = "Could not save Core viewer preferences." }
    }
}

enum CoreSelfTest {
    private final class Box: @unchecked Sendable {
        let lock = NSLock()
        var value: CoreUsage?
    }
    static func run(manifest: String, report: String) throws {
        let connection = try JSONDecoder().decode(CoreConnection.self, from: Data(contentsOf: URL(fileURLWithPath: manifest)))
        guard let url = connection.usageURL else { throw NSError(domain: "Core", code: 1) }
        var request = URLRequest(url: url)
        request.setValue("Bearer " + connection.token, forHTTPHeaderField: "Authorization")
        let delegate = LocalSession()
        let config = URLSessionConfiguration.ephemeral; config.connectionProxyDictionary = [:]
        let session = URLSession(configuration: config, delegate: delegate, delegateQueue: nil)
        defer { session.invalidateAndCancel() }
        let signal = DispatchSemaphore(value: 0), box = Box()
        session.dataTask(with: request) { data, response, error in
            defer { signal.signal() }
            if error == nil, (response as? HTTPURLResponse)?.statusCode == 200, let data,
               let sample = try? JSONDecoder().decode(CoreUsage.self, from: data), sample.valid() {
                box.lock.lock(); box.value = sample; box.lock.unlock()
            }
        }.resume()
        guard signal.wait(timeout: .now() + 6) == .success else { throw NSError(domain: "Core", code: 2) }
        box.lock.lock(); let value = box.value; box.lock.unlock()
        guard let sample = value else { throw NSError(domain: "Core", code: 3) }
        let result: [String: Any] = ["valid": true, "apps": sample.apps.count, "program": sample.program]
        let file = URL(fileURLWithPath: report)
        try JSONSerialization.data(withJSONObject: result).write(to: file, options: .atomic)
        try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: file.path)
    }
}
